package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log/slog"
	"os"
	"strings"
	"time"
	"unicode"

	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

const (
	GEN_MARKER = "//genQuery"
)

var validTypes map[string]string = map[string]string{
	"int":   "IntField",
	"int16": "IntField",
	"int32": "IntField",
	"int64": "IntField",

	"uint":   "IntField",
	"uint8":  "IntField",
	"uint16": "IntField",
	"uint32": "IntField",
	"uint64": "IntField",

	"float32":   "FloatField",
	"float64":   "FloatField",
	"uuid.UUID": "UUIDField",
	"time.Time": "DateTimeField",
	"bool":      "BoolField",
	"string":    "StringField",
}

type GenCtx struct {
	line, path, pkg string
}

func (g *GenCtx) Line() string    { return g.line }
func (g *GenCtx) Path() string    { return g.path }
func (g *GenCtx) Package() string { return g.pkg }

type GenField struct {
	Name string
	Type string
}

type Generator struct {
	buf           *strings.Builder
	ctx           *GenCtx
	fs            *token.FileSet
	structMap     map[string][]*ast.FuncDecl
	targetStructs map[string][]GenField
}

func NewGenerator(ctx *GenCtx) *Generator {
	return &Generator{
		ctx:           ctx,
		buf:           &strings.Builder{},
		targetStructs: make(map[string][]GenField),
		structMap:     make(map[string][]*ast.FuncDecl),
	}
}

func (g *Generator) getLine(node ast.Node) int {
	return g.fs.Position(node.Pos()).Line
}

func (g *Generator) processFn(decl *ast.FuncDecl) {
	if decl.Recv.List == nil {
		return
	}
	var structName string

	switch recv := decl.Recv.List[0].Type.(type) {
	case *ast.StarExpr:
		structName = recv.X.(*ast.Ident).Name
	case *ast.Ident:
		structName = recv.Name
	}

	g.structMap[structName] = append(g.structMap[structName], decl)
}

func (g *Generator) discoverStructs() {
	g.fs = token.NewFileSet()
	file, err := parser.ParseFile(g.fs, g.ctx.path, nil, parser.ParseComments)
	if err != nil {
		panic(err)
	}

	slog.Debug("parsed AST file", "name", file.Name.Name, "goVersion", file.GoVersion, "importsCount", len(file.Imports))

	var lineMap map[int]byte = make(map[int]byte)
	var fileStructMap map[string]*ast.TypeSpec = map[string]*ast.TypeSpec{}

	for _, c := range file.Comments {
		for _, k := range c.List {
			if strings.TrimSpace(k.Text) == GEN_MARKER {
				line := g.getLine(k)
				lineMap[line] = 1
				slog.Debug("found generator marker", "marker", GEN_MARKER, "line", line)
			}
		}
	}

	slog.Debug("marker line map", "linesCount", len(lineMap))

	for _, m := range file.Decls {
		switch decl := m.(type) {
		case *ast.FuncDecl:
			if decl.Recv != nil {
				g.processFn(decl)
			}

		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				if t, ok := spec.(*ast.TypeSpec); ok {
					if st, ok := t.Type.(*ast.StructType); ok {
						if _, ok = lineMap[g.getLine(st)-1]; ok {
							fileStructMap[t.Name.Name] = t
						}
					}
				}
			}
		}
	}

	for k, v := range fileStructMap {
		if _, ok := g.structMap[k]; !ok {
			continue
		}
		for _, f := range v.Type.(*ast.StructType).Fields.List {
			for _, n := range f.Names {
				if unicode.IsUpper([]rune(n.Name)[0]) {

					resolvedType := g.getValidExprType(f.Type)

					if resolvedType != "" {
						g.targetStructs[k] = append(g.targetStructs[k], GenField{
							Name: cases.Title(language.English).String(n.Name),
							Type: resolvedType,
						})
					}
					continue
				}
				for _, fns := range g.structMap[k] {
					if strings.EqualFold(n.Name, fns.Name.Name) {
						if unicode.IsUpper([]rune(n.Name)[0]) || unicode.IsUpper([]rune(fns.Name.Name)[0]) {

							resolvedType := g.getValidExprType(f.Type)

							if resolvedType != "" {
								g.targetStructs[k] = append(g.targetStructs[k], GenField{
									Name: cases.Title(language.English).String(n.Name),
									Type: resolvedType,
								})
							}
						}
					}

				}
			}
		}
	}

	slog.Info("discovered target structs", "count", len(g.targetStructs))
	slog.Debug("target struct definitions", "targets", g.targetStructs)
}

func (g *Generator) Generate() {
	slog.Info("starting struct discovery", "path", g.ctx.path)
	g.discoverStructs()
	slog.Info("generating query filter structs")
	g.writePackage()
	g.writeQueryStub()
}

func (g *Generator) GetCode() string {
	return g.buf.String()
}

func (g *Generator) Sync(fileName string) {
	if fileName == "" {
		fileName = g.ctx.path + "_query.go"
	}
	if err := os.WriteFile(fileName, []byte(g.buf.String()), 0666); err != nil {
		slog.Error("error writing to generated file", "file", fileName, "error", err)
		return
	}
	slog.Info("successfully wrote generated query struct file", "file", fileName)
}

func (g *Generator) writePackage() {
	v := g.buf

	v.WriteString(`// Auto Generated by go-filter tool. DO NOT EDIT or MODIFY. Generated at `)
	v.WriteString(time.Now().Format(time.DateTime))
	v.WriteString(".\n// go-filter Version : ")
	v.WriteString(Version)
	v.WriteString("\npackage ")
	v.WriteString(g.ctx.pkg)
	v.WriteString("\n\n")
	v.WriteString("import(\n\t\"github.com/XPD-Kasun/filters/fields\"\n)\n\n")
}

func (g *Generator) writeQueryStub() {
	v := g.buf

	for structName, fields := range g.targetStructs {
		v.WriteString("type ")
		v.WriteString(Pascal(structName))
		v.WriteString("Filter struct {\n")

		for _, field := range fields {
			v.WriteRune('\t')
			v.WriteString(field.Name)
			v.WriteRune(' ')
			if field.Type[0] == '*' {
				v.WriteString("fields.")
				v.WriteString(validTypes[field.Type[1:]])
			} else {
				v.WriteString("fields.")
				v.WriteString(validTypes[field.Type])
			}
			v.WriteRune('[')
			v.WriteString(structName)
			v.WriteRune(']')
			v.WriteRune('\n')
		}

		v.WriteString("}\n\n")

		v.WriteString("func New")
		v.WriteString(Pascal(structName))
		v.WriteString("Filter() *")
		v.WriteString(Pascal(structName))
		v.WriteString("Filter{\n")
		v.WriteString("\treturn &")
		v.WriteString(Pascal(structName))
		v.WriteString("Filter{\n")
		for _, field := range fields {
			v.WriteString("\t\t")
			v.WriteString(field.Name)
			v.WriteString(": ")
			if field.Type[0] == '*' {
				v.WriteString("fields.New")
				v.WriteString(validTypes[field.Type[1:]])
				v.WriteString(fmt.Sprintf(`[%s]("%s","%s"),%c`, structName, field.Name, Pascal(structName), '\n'))
			} else {
				v.WriteString("fields.New")
				v.WriteString(validTypes[field.Type])
				v.WriteString(fmt.Sprintf(`[%s]("%s","%s"),%c`, structName, field.Name, Pascal(structName), '\n'))
			}
		}
		v.WriteString("\t}\n")
		v.WriteString("}\n")
	}
}

func (g *Generator) getValidExprType(tn ast.Expr) string {
	var i = 0
	resolvedType := g.getExprType(tn)
	if resolvedType[0] == '*' {
		i = 1
	}
	if _, ok := validTypes[resolvedType[i:]]; ok {
		return resolvedType
	}
	return ""
}

func (g *Generator) getExprType(typeName ast.Expr) string {
	switch q := typeName.(type) {
	case *ast.Ident:
		return q.Name
	case *ast.SelectorExpr:
		return fmt.Sprintf("%s.%s", q.X.(*ast.Ident).Name, q.Sel.Name)
	case *ast.StarExpr:
		return "*" + g.getExprType(q.X)
	}
	return ""
}
